import { recorder } from "./rec.mjs";
import { idle, sz } from "./lib.mjs";
export default async ({ page, args }) => {
  await sz(page);
  // Start from a closed editor so the recording opens the file.
  await page.getByText("Workspace", { exact: true }).first().click();
  await page.waitForTimeout(800);
  const closeTab = page.getByRole("button", { name: /close/i }).filter({ visible: true });
  if (await closeTab.count()) await closeTab.first().click().catch(() => {});
  await page.getByText("New Chat", { exact: true }).first().click();
  await page.waitForTimeout(800);
  await page.mouse.move(900, 600);
  const r = await recorder(page, args[0]);
  await r.start();
  await page.waitForTimeout(500);
  await r.clickLocator(page.getByText("Workspace", { exact: true }).first(), 0.4, 0.5);
  r.mark("workspace");
  await page.waitForTimeout(900);
  await r.clickLocator(page.getByText(/^compose\.workflo/).first(), 0.4, 0.5);
  r.mark("open-file");
  await page.waitForTimeout(1200);
  await r.move(900, 560, 16);
  r.mark("read-code");
  await page.waitForTimeout(1800);
  await r.clickLocator(page.getByText("New Chat", { exact: true }).first(), 0.4, 0.5);
  r.mark("new-chat");
  await page.waitForTimeout(900);
  await r.clickLocator(page.locator("[aria-label=Message]:visible").last(), 0.3, 0.5);
  await page.keyboard.type("Run @compo", { delay: 30 });
  await page.waitForTimeout(900);
  r.mark("mention");
  await page.keyboard.press("Enter");
  await page.waitForTimeout(300);
  await page.keyboard.type(" on: a one-line tagline for a developer tool. Reply with the tagline only.", { delay: 14 });
  await page.waitForTimeout(300);
  await r.clickLocator(page.locator('[aria-label="Send message"]:visible').last());
  r.mark("send");
  await idle(page, 400000);
  r.mark("done");
  await page.waitForTimeout(1500);
  await r.stop();
};
