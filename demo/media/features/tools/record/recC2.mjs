import { recorder } from "./rec.mjs";
import { idle } from "./lib.mjs";
export default async ({ page, args }) => {
  await page.waitForTimeout(1500);
  const r = await recorder(page, args[0]);
  await page.mouse.move(900, 500);
  await r.start();
  await page.waitForTimeout(700);
  await r.clickLocator(page.getByText("Developer Tool Pricing", { exact: false }).first(), 0.3, 0.5);
  r.mark("open-chat");
  await page.waitForTimeout(1600);
  const marker = page.getByText("A free tier brings in users", { exact: true }).filter({ visible: true }).first();
  const b = await marker.boundingBox();
  await r.move(b.x + b.width * 0.5, b.y + b.height * 0.6, 14);
  r.mark("hover-marker");
  await page.waitForTimeout(700);
  await r.click(b.x + b.width * 0.5, b.y + b.height * 0.6);
  r.mark("open-digin");
  await page.waitForTimeout(1500);
  await r.clickLocator(page.locator('[data-slot="model-selector-trigger"]:visible').last());
  r.mark("picker");
  await page.waitForTimeout(700);
  const opt = page.getByRole("option", { name: /^Opus 5.5/ }).first();
  await opt.scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  await r.clickLocator(opt, 0.3, 0.5);
  r.mark("picked");
  await page.waitForTimeout(400);
  await r.clickLocator(page.locator("[aria-label=Message]:visible").last(), 0.3, 0.5);
  await page.keyboard.type("And the paid tier? Two short bullets.", { delay: 18 });
  await page.waitForTimeout(200);
  await r.clickLocator(page.locator('[aria-label="Send message"]:visible').last());
  r.mark("send");
  await idle(page);
  r.mark("done");
  await page.waitForTimeout(1200);
  await r.stop();
};
